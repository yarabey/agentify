// Package pgbackup содержит воспроизводимую проверку резервного копирования и
// восстановления Postgres (тикет 11.5, FR I2).
//
// # Назначение (бизнес)
//
// История задач/событий в agentify хранится бессрочно (FR I2,
// docs/01_tech_stack §"Бэкап БД"). Регулярный pg_dump (сервис backup,
// deploy/docker-compose.backup.yml) — страховка от потери этой истории, но
// бэкап ценен, только если из него реально ВОССТАНАВЛИВАЮТСЯ данные. Этот пакет
// автоматизирует приёмку «восстановление из дампа на чистый инстанс проходит».
//
// # Как устроено (тех)
//
// Продакшн-логика бэкапа живёт в shell-скриптах (deploy/backup/backup.sh —
// pg_dump по cron; deploy/backup/restore-check.sh — ручная проверка
// восстановления на throwaway-инстансе). Go-кода в рантайме бэкап не требует,
// поэтому здесь нет экспортируемых символов — только integration-тест
// (файл с тегом build integration): он поднимает Postgres на testcontainers,
// наполняет данными, снимает pg_dump, поднимает ВТОРОЙ чистый Postgres,
// восстанавливает дамп через pg_restore и проверяет, что данные на месте.
// Тест повторяет ровно ту механику, что и скрипты (custom-формат -Fc +
// pg_restore), и гоняется в CI-джобе integration (`go test -tags=integration`).
