// Package db — слой доступа к данным оркестратора: sqlc-сгенерированные
// запросы/модели (db.go, models.go, *.sql.go — не редактируются вручную, см.
// orchestrator/queries и sqlc.yaml) поверх pgx/v5, плюс рукописные хелперы
// этого же слоя, которым не место в сгенерированном коде (SetAppUserID, RLS —
// тикет 1.5).
package db

// rls.go — Go-сторона изоляции данных между пользователями (тикет 1.5, FR A4,
// I3, Gherkin §1 «Изоляция данных между пользователями»).
//
// Назначение (бизнес): данные одного пользователя (tasks, integrations)
// никогда не должны быть видны или доступны другому. Основной механизм —
// обязательный фильтр по user_id в каждом запросе к tasks/integrations на
// уровне приложения (его пишут будущие обработчики EPIC 2/5 — CRUD для
// tasks/integrations ещё не реализован на момент этого тикета). Postgres
// Row Level Security (orchestrator/migrations/00005_rls.sql, не
// редактируется этим тикетом) — страховка поверх этого фильтра: даже если
// обработчик где-то забудет добавить WHERE user_id = ..., RLS-политика
// `USING (user_id = current_setting('app.user_id', true)::uuid)` на стороне
// БД молча не вернёт чужие строки.
//
// Как устроено (тех): RLS-политика читает сессионную (а не транзакционную в
// смысле SQL-стандарта, но именно так используется здесь — см. ниже)
// переменную app.user_id через current_setting(..., missing_ok=true). Чтобы
// её туда положить, приложение обязано в начале каждой транзакции, работающей
// с tasks/integrations, вызвать SetAppUserID — этот вызов выполняет
// `SELECT set_config('app.user_id', $1, true)` ПАРАМЕТРИЗОВАННО (значение
// идёт как bind-параметр pgx, а не конкатенацией в текст SQL — иначе
// получили бы SQL-инъекцию через значение, которое в обычном потоке
// безопасно, потому что приходит из уже провалидированного access-токена, но
// конкатенация всё равно была бы плохой практикой и сломалась бы при
// нестандартных значениях). Третий аргумент set_config — is_local=true:
// значение действует только до конца ТЕКУЩЕЙ транзакции и автоматически
// сбрасывается при COMMIT/ROLLBACK — то есть это именно транзакционная
// область видимости, а не у соединения целиком, что важно при переиспользовании
// соединений из пула (pgxpool) между запросами разных пользователей.
//
// Если SetAppUserID не вызвать вовсе, current_setting(..., true) внутри
// политики вернёт NULL, сравнение `user_id = NULL` даёт NULL (не TRUE) —
// политика по умолчанию отказывает в доступе ко ВСЕМ строкам (fail-closed),
// что и проверяет orchestrator/internal/db/rls_integration_test.go.
//
// Нюанс пула соединений (обнаружен эмпирически при написании интеграционного
// теста — orchestrator/internal/db/rls_integration_test.go, пункт 7; не
// очевиден из текста 00005_rls.sql, поэтому фиксируем здесь явно): описанное
// выше "current_setting возвращает NULL" верно ТОЛЬКО для физического
// соединения, на котором set_config('app.user_id', ...) ещё ни разу не
// вызывался. Как только это произошло хотя бы раз в рамках сессии (даже если
// значение было локальным для транзакции, is_local=true, и транзакция
// закоммичена/откачена), Postgres заводит у себя placeholder для этого
// custom-GUC и при последующих "сбросах" возвращает не "переменная не
// существует" (-> NULL), а пустую строку ''. current_setting(..., true) в
// этом случае возвращает '' вместо NULL, а `''::uuid` в политике падает с
// SQL-ошибкой 22P02 (invalid_text_representation) вместо тихого "0 строк".
// Для безопасности это РАВНОЦЕННО fail-closed (чужая строка никогда не
// попадает в результат — запрос целиком обрывается ошибкой), но это означает,
// что при переиспользовании соединений пулом (pgxpool — обычный режим работы
// приложения) "забыли вызвать SetAppUserID" может проявиться как 500, а не
// как аккуратные пустые 404/[] — поэтому вызов SetAppUserID в начале КАЖДОЙ
// транзакции, работающей с tasks/integrations, обязателен без исключений, а
// не "защитная мера на всякий случай".

import (
	"context"
	"fmt"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
)

// SetAppUserID выставляет сессионную переменную app.user_id для текущей
// транзакции tx — её читает RLS-политика tasks/integrations (FR A4, I3).
//
// Вызывать в самом начале транзакции, ДО любых запросов к
// tasks/integrations в её рамках (см. godoc файла) — будущие обработчики
// CRUD tasks/integrations (EPIC 2/5) обязаны делать это первым шагом после
// pool.Begin/BeginTx. userID берётся из контекста запроса через
// api.UserIDFromContext (тот же google/uuid.UUID, что использует
// auth-middleware, тикет 1.4) — этот пакет (orchestrator/internal/db) не
// импортирует api, поэтому конвертация userID -> строка происходит здесь, а
// извлечение из контекста остаётся на вызывающей стороне.
//
// set_config выбран вместо `SET LOCAL app.user_id = ...` намеренно: SET не
// поддерживает bind-параметры (PostgreSQL не позволяет параметризовать имена/
// значения в SET через protocol-level параметры), поэтому пришлось бы
// собирать SQL конкатенацией строк — set_config(name, value, is_local)
// обычная функция, value — заданный параметр запроса ($1), что исключает
// инъекцию в принципе, а не только при «корректных» значениях.
func SetAppUserID(ctx context.Context, tx pgx.Tx, userID uuid.UUID) error {
	if _, err := tx.Exec(ctx, `SELECT set_config('app.user_id', $1, true)`, userID.String()); err != nil {
		return fmt.Errorf("set_config app.user_id: %w", err)
	}
	return nil
}
