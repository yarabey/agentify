// Package task — конечный автомат (FSM) статусов задачи (тикет 5.2, FR E1,
// docs/"Жизненный цикл задачи.md").
//
// Назначение (бизнес): статус задачи — центральное состояние всего
// жизненного цикла (Gherkin §4–§10): пользователь ставит задачу, машина её
// выполняет, возможны уточняющие вопросы и согласования команд, агент
// сообщает о завершении — но задача считается «завершена» ТОЛЬКО после
// явного подтверждения пользователем (FR E2), а не по одному только
// сообщению агента. NextStatus — единственная таблица допустимых переходов,
// переносящая mermaid-диаграмму docs/"Жизненный цикл задачи.md" дословно в
// код: любой недопустимый переход отклоняется на этом уровне, ДО попытки
// записи в БД. Transition — единственная точка смены tasks.status в БД:
// атомарно (одна транзакция) читает актуальный статус под блокировкой
// строки, проверяет переход через NextStatus и пишет
// tasks.status/updated_at вместе с task_events(status_change) (FR F2, F4 —
// аудит и история).
//
// Явно ВНЕ объёма этого тикета:
//   - Кто и когда вызывает Transition с каким Trigger (обработка конкретных
//     сообщений протокола machine.events/commands, HTTP-хендлеры
//     подтверждения/отмены и т.д.) — последующие тикеты EPIC 5/6/8
//     (5.3–5.8, 6.x, 8.x), которые будут использовать Transition как готовый
//     примитив.
//   - Шифрование payload_enc (TODO(11.1)): этот тикет отвечает только за
//     FR E1 (сама FSM); единый крипто-модуль AEAD для
//     text_enc/payload_enc/uuid_enc — тикет 11.1 (FR I1).
//   - STALE_THRESHOLD/таймауты (тикет 5.7) и обработка ошибок агента/машины
//     (тикет 5.8) сами по себе — этот пакет только предоставляет переходы
//     TriggerTimeout/TriggerAgentError как примитив FSM.
//
// Как устроено (тех):
//   - fsm.go — чистые типы Status/Trigger и таблица transitions +
//     NextStatus, без обращения к БД.
//   - transition.go — Transitioner держит *pgxpool.Pool напрямую (а не узкий
//     sqlc-интерфейс, как presence/api) и сам открывает транзакцию: первый
//     пакет оркестратора с многошаговой транзакцией
//     (SELECT ... FOR UPDATE + UPDATE + INSERT).
