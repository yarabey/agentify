// Package hello — временный hello-world пакет оркестратора.
//
// Назначение (бизнес): первичный каркас сервиса-оркестратора (FR E*),
// нужный, чтобы тикет 0.1 имел реально собираемый и тестируемый код
// до появления REST+WS/FSM/auth в последующих тикетах EPIC 0/3.
//
// Как устроено (тех): пакет содержит единственную чистую функцию Greeting,
// возвращающую приветствие сервиса. Он намеренно не имеет внешних
// зависимостей, чтобы make lint/test были зелёными на «пустом» проекте.
// Будет вытеснен реальными пакетами оркестратора в тикетах 0.6 и EPIC 3.
package hello

// ServiceName — каноническое имя сервиса-оркестратора, используемое в логах
// и приветствии. Зафиксировано здесь, чтобы переиспользоваться при сборке
// каркаса в тикете 0.6.
const ServiceName = "orchestrator"

// Greeting возвращает приветственную строку сервиса-оркестратора.
//
// Это заглушка тикета 0.1: она существует, чтобы дать make test реальный
// предмет проверки и продемонстрировать дисциплину godoc/тестов из AGENTS.md §3.
func Greeting() string {
	return "hello from " + ServiceName
}
